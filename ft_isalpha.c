#include "libft.h"

int	ft_isalpha(int text)
{
	if (text >= 'A' && text <= 'Z')
	{
		return (1);
	}
	else if (text >= 'a' && text <= 'z')
	{
		return (1);
	}
	else
	{
		return (0);
	}
}
